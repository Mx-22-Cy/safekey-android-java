package com.safekey.app.securityui;

import android.graphics.Bitmap;
import android.graphics.Color;

import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.WriterException;
import com.google.zxing.common.BitMatrix;
import com.google.zxing.qrcode.QRCodeWriter;

import java.util.EnumMap;
import java.util.Map;

/** Local-only rendering: never transmit or log an otpauth URI. */
final class TotpQrCodeRenderer {
    private TotpQrCodeRenderer() { }

    static Bitmap render(String uri, int size) throws WriterException {
        Map<EncodeHintType, Object> hints = new EnumMap<>(EncodeHintType.class);
        hints.put(EncodeHintType.MARGIN, 2);
        BitMatrix bits = new QRCodeWriter().encode(uri, BarcodeFormat.QR_CODE, size, size, hints);
        int width = bits.getWidth();
        int height = bits.getHeight();
        int[] pixels = new int[width * height];
        for (int y = 0; y < height; y++) {
            for (int x = 0; x < width; x++) {
                pixels[y * width + x] = bits.get(x, y) ? Color.BLACK : Color.WHITE;
            }
        }
        Bitmap bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888);
        bitmap.setPixels(pixels, 0, width, 0, 0, width, height);
        java.util.Arrays.fill(pixels, 0);
        return bitmap;
    }
}
